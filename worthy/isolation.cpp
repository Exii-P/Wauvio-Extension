static StereoBuffer make_harp(double freq, double dur, double amp)
{
    double d = std::max(0.10, std::min(dur, 1.2));
    Buffer mono = make_buffer(d, SR);

    Oscillator o1(WaveShape::Triangle, freq,       amp * 0.60);
    Oscillator o2(WaveShape::Sine,     freq * 2.0, amp * 0.28);
    Oscillator o3(WaveShape::Sine,     freq * 3.0, amp * 0.10);
    Oscillator o4(WaveShape::Sine,     freq * 4.0, amp * 0.04);
    for (auto& s : mono) s = o1.tick(SR) + o2.tick(SR) + o3.tick(SR) + o4.tick(SR);

    std::vector<AutoPoint> cut = {
        {0.0,    10000.0f},
        {0.012,   6000.0f},
        {0.15,    2500.0f},
        {d,       800.0f}
    };
    mono = apply_filter_automation(mono, cut, 1.2, SVFilter::Mode::LowPass, SR);

    for (size_t i = 0; i < mono.size(); ++i) {
        double t = (double)i / SR;
        double env = (t < 0.004) ? (t / 0.004) : std::exp(-(t - 0.004) * 5.5);
        mono[i] *= (float)env;
    }
    return haas_widen(mono, 8.0, SR);
}

