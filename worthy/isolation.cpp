static void mix_mono_at(StereoBuffer& dst, const Buffer& src,
                        double t_sec, float gain, int sr)
{
    const size_t off = (size_t)(t_sec * sr);
    for (size_t i = 0; i < src.size() && off + i < dst.size(); ++i) {
        dst.L[off + i] += src[i] * gain;
        dst.R[off + i] += src[i] * gain;
    }
}
static void mix_stereo_at(StereoBuffer& dst, const StereoBuffer& src,
                          double t_sec, float gain, int sr)
{
    const size_t off = (size_t)(t_sec * sr);
    for (size_t i = 0; i < src.size() && off + i < dst.size(); ++i) {
        dst.L[off + i] += src.L[i] * gain;
        dst.R[off + i] += src.R[i] * gain;
    }
}

static Buffer make_violin(double freq, double dur, double amp)
{
    if (dur <= 0.0 || freq < 10.0) return make_buffer(std::max(0.001, dur), SR);
    Buffer buf = make_buffer(dur, SR);

    Oscillator o1(WaveShape::BL_Sawtooth, freq,        amp * 0.55);
    Oscillator o2(WaveShape::BL_Sawtooth, freq * 1.005, amp * 0.35);

    Oscillator o3(WaveShape::Sine,        freq * 3.0,  amp * 0.10);

    double vib_phase = 0.0;
    const double vib_rate = 5.5;
    const double vib_depth = freq * (std::pow(2.0, 8.0/1200.0) - 1.0);

    for (size_t i = 0; i < buf.size(); ++i) {
        vib_phase += TWO_PI * vib_rate / SR;
        if (vib_phase >= TWO_PI) vib_phase -= TWO_PI;

        double t = (double)i / SR;
        double vib_env = std::min(1.0, std::max(0.0, (t - 0.15) / 0.10));
        double vib = std::sin(vib_phase) * vib_depth * vib_env;
        o1.frequency = freq        + vib;
        o2.frequency = freq * 1.005 + vib;
        buf[i] = o1.tick(SR) + o2.tick(SR) + o3.tick(SR);
    }

    BiquadEQ form(BiquadEQ::Type::Peak, 2500.0, 4.0, 2.5);
    form.process(buf, SR);

    HighPassFilter hpf(180.0, SR);
    hpf.process(buf);

    double rel = std::min(0.40, dur * 0.25);
    DAHDSR env(0.0, std::min(0.08, dur*0.15), 0.0, dur*0.08, 0.82, rel);
    env.apply(buf, dur, std::max(0.0, dur-rel), SR);
    return buf;
}

static Buffer make_cello(double freq, double dur, double amp)
{
    if (dur <= 0.0 || freq < 10.0) return make_buffer(std::max(0.001, dur), SR);
    Buffer buf = make_buffer(dur, SR);

    Oscillator o1(WaveShape::BL_Sawtooth, freq,        amp * 0.50);
    Oscillator o2(WaveShape::BL_Sawtooth, freq * 2.0,  amp * 0.22);
    Oscillator o3(WaveShape::Sine,        freq * 0.5,  amp * 0.28);

    double fl_phase = 0.0;
    for (size_t i = 0; i < buf.size(); ++i) {
        fl_phase += TWO_PI * 6.0 / SR;
        if (fl_phase >= TWO_PI) fl_phase -= TWO_PI;
        float tremolo = 1.0f + 0.04f * (float)std::sin(fl_phase);
        buf[i] = (o1.tick(SR) + o2.tick(SR) + o3.tick(SR)) * tremolo;
    }

    BiquadEQ body(BiquadEQ::Type::Peak, 320.0, 3.5, 1.8);
    body.process(buf, SR);
    SVFilter lp(SVFilter::Mode::LowPass, 4500.0, 0.7);
    lp.process(buf, SR);

    double atk = std::min(0.12, dur * 0.20);
    double rel = std::min(0.50, dur * 0.28);
    DAHDSR env(0.0, atk, 0.0, dur * 0.12, 0.80, rel);
    env.apply(buf, dur, std::max(0.0, dur-rel), SR);
    return buf;
}

