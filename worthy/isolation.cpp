static Buffer make_timpani(double pitch_freq = 90.0)
{
    const double dur = 1.20;
    Buffer buf = make_buffer(dur, SR);
    double phase = 0.0;
    NoiseGenerator ng(41u);
    for (size_t i = 0; i < buf.size(); ++i) {
        double t = (double)i / SR;

        double f = pitch_freq * (1.0 + 0.12 * std::exp(-t * 12.0));
        phase += TWO_PI * f / SR;
        if (phase >= TWO_PI) phase -= TWO_PI;
        float tone  = (float)(std::sin(phase) * std::exp(-t * 4.5));
        float noise = ng.tick_white() * (float)std::exp(-t * 30.0) * 0.18f;
        buf[i] = tone + noise;
    }
    SVFilter lp(SVFilter::Mode::LowPass, 420.0, 0.8);
    lp.process(buf, SR);
    normalize(buf, 0.90f);
    return buf;
}

